#!/usr/bin/env python3
"""Generate assets/js/data.js from data/portfolio.json.

The browser reads window.PF_DATA (works from file://, no fetch needed) and the
backend reads the JSON directly, so there is one source of truth.
Usage: python scripts/build_data.py [--check]   (--check fails if data.js is stale)
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "data" / "portfolio.json", ROOT / "assets" / "js" / "data.js"

def render() -> str:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    data.pop("_note", None)
    body = json.dumps(data, indent=1, ensure_ascii=False).replace("</", "<\\/")
    return f"/* GENERATED by scripts/build_data.py from data/portfolio.json. Do not edit. */\nwindow.PF_DATA = {body};\n"

if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != new:
            sys.exit("assets/js/data.js is out of date. Run: python scripts/build_data.py")
        print("data.js is up to date")
    else:
        OUT.write_text(new, encoding="utf-8"); print(f"wrote {OUT.relative_to(ROOT)}")
